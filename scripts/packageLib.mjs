// Builds the library and writes a self-contained, installable package into the given directory:
//   node scripts/packageLib.mjs ../signet/lib/reactgrid
// The consumer then depends on it with `"@silevis/reactgrid": "file:<dir>"`.
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const libraryRoot = resolve(repoRoot, "reactgrid");
const targetDir = process.argv[2] && resolve(process.cwd(), process.argv[2]);

if (!targetDir) {
  console.error("Usage: node scripts/packageLib.mjs <target directory>");
  process.exit(1);
}

const git = (...args) => execFileSync("git", args, { cwd: repoRoot, encoding: "utf8" }).trim();
const commit = git("rev-parse", "HEAD");
const branch = git("rev-parse", "--abbrev-ref", "HEAD");
const sourceUrl = git("remote", "get-url", "origin").replace(/^git@github\.com:/, "https://github.com/");
const isDirty = git("status", "--porcelain", "--", "reactgrid/lib", "reactgrid/package.json", "reactgrid/vite.config.ts") !== "";

if (isDirty) {
  console.error("The library has uncommitted changes; commit them first so the package records the commit it was built from.");
  process.exit(1);
}

// Build in place, then copy: the declaration roll-up only lands reliably in the library's own dist directory.
execFileSync("npm", ["run", "build"], { cwd: libraryRoot, stdio: "inherit" });

const targetDist = resolve(targetDir, "dist");
rmSync(targetDist, { recursive: true, force: true });
mkdirSync(targetDist, { recursive: true });
for (const artifact of ["main.js", "main.js.map", "main.d.ts"]) {
  copyFileSync(resolve(libraryRoot, "dist", artifact), resolve(targetDist, artifact));
}

const sourcePackage = JSON.parse(readFileSync(resolve(libraryRoot, "package.json"), "utf8"));
const peerDependencies = { react: sourcePackage.dependencies.react, "react-dom": sourcePackage.dependencies["react-dom"] };

// Everything but React is bundled into dist, so the package needs no dependencies of its own.
const packageJson = {
  name: sourcePackage.name,
  version: sourcePackage.version,
  description: `Mantle fork of ReactGrid built from ${branch}@${commit.slice(0, 7)}`,
  type: "module",
  main: "dist/main.js",
  types: "dist/main.d.ts",
  files: ["dist"],
  license: "MIT",
  repository: { type: "git", url: sourceUrl },
  gitHead: commit,
  peerDependencies,
};

writeFileSync(resolve(targetDir, "package.json"), `${JSON.stringify(packageJson, null, 2)}\n`);
copyFileSync(resolve(libraryRoot, "LICENSE"), resolve(targetDir, "LICENSE"));
writeFileSync(
  resolve(targetDir, "README.md"),
  `# @silevis/reactgrid (Mantle fork)

Production build of Mantle's ReactGrid fork, generated by \`scripts/packageLib.mjs\` in the fork repository. Do not edit by hand.

- Source: ${sourceUrl} (branch \`${branch}\`)
- Commit: \`${commit}\`
- Built: ${new Date().toISOString()}

To update, commit the change in the fork and run from the fork's root:

\`\`\`
node scripts/packageLib.mjs <path to this directory>
\`\`\`
`
);

console.log(`Packaged ${sourcePackage.name}@${sourcePackage.version} (${commit.slice(0, 7)}) into ${targetDir}`);
